func (n *Node) Spread(ctx context.Context, args *pb.State) (*pb.StateResponse, error) {
	cert, err := n.validateCtx(ctx)
	if err != nil {
		return nil, err
	}

	// cert.SubjectKeyId holds the remote peer.Id generated by the certificate authority
	// NOTE: this means we need to figure out how old peers renew their certificates and
	// how the id is updated. Currently, it's totally random
	remoteId := string(cert.SubjectKeyId[:])
	peer, wasObserved, wasAccused, err := n.admitCaller(cert, remoteId, args.GetOwnNote())
	if err != nil {
		return nil, err
	}

	reply := n.newStateResponse()

	if !n.view.ShouldBeNeighbour(remoteId) {
		return n.handleNonNeighbourSpread(peer, wasObserved, wasAccused, reply)
	}

	return reply, nil
}

func (n *Node) handleNonNeighbourSpread(peer *discovery.Peer, wasObserved bool, wasAccused bool, reply *pb.StateResponse) (*pb.StateResponse, error) {
	if wasObserved {
		if !wasAccused {
			return nil, errNotMyNeighbour
		}
		// the number of active accusations is bounded by the number of rings --
		// this acts as a fast path to piggyback active accusations that are on a
		// timer
		for _, a := range n.view.ActiveAccusationsForPeer(peer) {
			reply.Accusations = append(reply.Accusations, a.ToPbMsg())
		}
		return reply, nil
	}

	return reply, nil
}

func (n *Node) newStateResponse() *pb.StateResponse {
	return &pb.StateResponse{}
}

func serviceIDFromContext(ctx context.Context) (string, error) {
	md, ok := metadata.FromIncomingContext(ctx)
	if !ok {
		return "", status.Error(codes.InvalidArgument, "missing service-id metadata")
	}
	vals := md.Get(comm.ServiceIDMetadataKey)
	if len(vals) != 1 || vals[0] == "" {
		return "", status.Error(codes.InvalidArgument, "missing or invalid service-id metadata")
	}
	if err := discovery.ValidateServiceID(vals[0]); err != nil {
		return "", status.Errorf(codes.InvalidArgument, "invalid service-id %q: %v", vals[0], err)
	}
	return vals[0], nil
}

func (n *Node) Messenger(ctx context.Context, args *pb.Msg) (*pb.MsgResponse, error) {
	var errMsg string
	var replyContent []byte

	_, err := n.validateCtx(ctx)
	if err != nil {
		return nil, err
	}

	serviceID, err := serviceIDFromContext(ctx)
	if err != nil {
		return nil, err
	}

	handler := n.getServiceMsgHandler(serviceID)
	if handler == nil {
		return nil, status.Errorf(codes.NotFound, "no message handler registered for service %q", serviceID)
	}

	replyContent, err = handler(args.GetContent())
	if err != nil {
		errMsg = err.Error()
	}
	return &pb.MsgResponse{Content: replyContent, Error: errMsg}, nil
}

func (n *Node) Stream(srv pb.Gossip_StreamServer) error {
	ctx := srv.Context()
	if _, err := n.validateCtx(ctx); err != nil {
		return err
	}

	serviceID, err := serviceIDFromContext(ctx)
	if err != nil {
		return err
	}

	handler := n.getServiceStreamHandler(serviceID)
	if handler == nil {
		return status.Errorf(codes.NotFound, "no stream handler registered for service %q", serviceID)
	}

	// Channels used for bi-directional communication
	input := make(chan []byte)
	reply := make(chan []byte)

	// Concurrency guard: Ensure replyStream finishes transmitting all generated responses
	// before Stream() returns. Returning early on io.EOF cancels the gRPC stream context
	// on the server, prematurely severing the connection and dropping in-flight responses.
	replyDone := make(chan struct{})
	go func() {
		defer close(replyDone)
		n.replyStream(reply, srv)
	}()

	go n.runStreamHandler(handler, input, reply)

	var recvErr error

	for {
		select {
		case <-ctx.Done():
			recvErr = ctx.Err()
			goto done
		default:
		}

		req, err := srv.Recv()
		if err == io.EOF {
			break
		}
		if err != nil {
			recvErr = err
			break
		}

		select {
		case <-ctx.Done():
			recvErr = ctx.Err()
			goto done
		case input <- req.GetContent():
		}
	}

done:
	// Signal to stream handler that client has closed its send side (no more inputs).
	close(input)

	// Wait for handler to finish processing remaining messages and replyStream to flush
	// all replies across the gRPC transport before completing the RPC.
	<-replyDone

	if recvErr != nil && recvErr != io.EOF {
		return recvErr
	}
	return nil
}

func (n *Node) replyStream(reply chan []byte, srv pb.Gossip_StreamServer) {
	for resp := range reply {
		responseMsg := &pb.MsgResponse{
			Content: resp,
		}

		if err := srv.Send(responseMsg); err != nil {
			log.Error(err.Error())
		}
	}
}

func (n *Node) runStreamHandler(handler streamMsg, input, reply chan []byte) {
	handler(input, reply)
}
