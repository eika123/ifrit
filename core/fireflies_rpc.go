const defaultAnnounceTimeout = 10 * time.Second

var (
	errNoPeerInCtx            = errors.New("No peer information found in provided context.")
	errNoTLSInfo              = errors.New("No TLS info provided in peer context.")
	errNeighbourPeerNotFound  = errors.New("Neighbour peer was not found.")
	errNotMyNeighbour         = errors.New("Invalid gossip partner, not my neighbour.")
	errInvalidPeerInformation = errors.New("Could not create local peer representation.")
	errInvalidMaskLength      = errors.New("Mask is of invalid length.")

	errAccAlreadyExists      = errors.New("Accusation already existed, discarding.")
	errDisabledRing          = errors.New("Ring associated with accusation was disabled.")
	errInvalidAccuser        = errors.New("Accuser is not predecessor of accused on given ring, invalid accusation.")
	errInvalidSignature      = errors.New("Signature was invalid.")
	errInvalidSelfAccusation = errors.New("Received accusation about myself, but it was invalid.")
	errInvalidEpoch          = errors.New("Accusation epoch did not match note epoch.")

	errInvalidMask = errors.New("Note contained invalid mask")
	errOldNote     = errors.New("Already had the same or a more recent note")
	errNoPeer      = errors.New("Peer associated with note not found in full view.")

	errNilCert   = errors.New("Certificate was nil.")
	errSelfCert  = errors.New("Certificate was my own.")
	errNoCert    = errors.New("No certificate present in tls context.")
	errInvalidId = errors.New("Id in certificate is of invalid size.")
)

type firefliesRPCServer struct {
	pb.UnimplementedFirefliesServer
	node *Node
}

func (s *firefliesRPCServer) Announce(ctx context.Context, args *pb.AnnounceRequest) (*pb.AnnounceResponse, error) {
	return s.node.handleAnnounce(ctx, args)
}

func (n *Node) handleAnnounce(ctx context.Context, args *pb.AnnounceRequest) (*pb.AnnounceResponse, error) {
	cert, err := n.validateCtx(ctx)
	if err != nil {
		return nil, err
	}

	// cert.SubjectKeyId holds the remote peer.Id generated by the certificate authority
	// NOTE: this means we need to figure out how old peers renew their certificates and
	// how the id is updated. Currently, it's totally random
	remoteId := string(cert.SubjectKeyId[:])
	if args.GetOwnNote() != nil {
		if existing := n.view.Peer(remoteId); existing != nil {
			incomingNote := discovery.NoteFromPb(args.GetOwnNote())
			if (args.GetIsRebuttal() || n.view.IsRebuttal(existing, incomingNote)) &&
				n.AdversarialPolicy().shouldDropIncomingRebuttal(existing, incomingNote) {
				log.Debug("Adversary: dropped incoming Announce rebuttal", "peer", remoteId)
				return n.newAnnounceResponse(), nil
			}
		}
	}
	peer, wasObserved, wasAccused, err := n.admitCaller(cert, remoteId, args.GetOwnNote())
	if err != nil {
		return nil, err
	}

	reply := n.newAnnounceResponse()

	if !n.view.ShouldBeNeighbour(remoteId) {
		return n.handleNonNeighbourAnnounce(peer, wasObserved, wasAccused, reply)
	}

	return reply, nil
}

func (n *Node) handleNonNeighbourAnnounce(peer *discovery.Peer, wasObserved bool, wasAccused bool, reply *pb.AnnounceResponse) (*pb.AnnounceResponse, error) {
	if wasObserved {
		if !wasAccused {
			return nil, errNotMyNeighbour
		}
		// the number of active accusations is bounded by the number of rings --
		// this acts as a fast path to piggyback active accusations that are on a
		// timer
		for _, a := range n.view.ActiveAccusationsForPeer(peer) {
			reply.Accusations = append(reply.Accusations, a.ToPbMsg())
		}
		return reply, nil
	}

	return reply, nil
}

func (n *Node) newAnnounceResponse() *pb.AnnounceResponse {
	return &pb.AnnounceResponse{}
}

func (n *Node) announce(ctx context.Context, addr string, req *pb.AnnounceRequest) (*pb.AnnounceResponse, error) {
	if n.announceFn != nil {
		return n.announceFn(ctx, addr, req)
	}
	cc, err := n.comm.ClientConn(addr)
	if err != nil {
		return nil, err
	}
	if cc == nil {
		return nil, errors.New("comm returned nil client connection")
	}
	if ctx == nil {
		ctx = context.Background()
	}
	callCtx, cancel := context.WithTimeout(ctx, defaultAnnounceTimeout)
	defer cancel()

	return pb.NewFirefliesClient(cc).Announce(callCtx, req)
}
